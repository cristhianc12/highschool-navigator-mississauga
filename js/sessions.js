/** Adds sessions collected later (see details.js) and keeps the list sorted by date. */
let nx = 0;
export function addSessions(list) {
  for (const o of list) {
    const k = key(o.school);
    // skip an event that is already listed (same school, kind, date and time)
    if (SESSIONS.some((e) => e.key === k && e.kind === o.kind && e.date === (o.date || null) && (e.time || null) === (o.time || null))) continue;
    SESSIONS.push({ id: `x${++nx}`, ...o, key: k });
  }
  SESSIONS.sort((a, b) => (a.date || "9999").localeCompare(b.date || "9999") || (a.time || "99").localeCompare(b.time || "99") || a.school.localeCompare(b.school));
}

/** Sessions relevant to a school profile (matches by school name). */
export const sessionsForSchool = (school) => {
  const k = key(school.name);
  return SESSIONS.filter((e) => e.key === k);
};

/** Sessions for a regional program, across its host schools. */
export const sessionsForProgram = (program) => SESSIONS.filter((e) => e.programId === program.id || (e.kind === "school" && (e.programIds || []).some((p) => p.id === program.id)));

/* ---------------- formatting and calendar ---------------- */

const MONTHS = { es: ["ene", "feb", "mar", "abr", "may", "jun", "jul", "ago", "sep", "oct", "nov", "dic"], en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"], fr: ["janv.", "févr.", "mars", "avr.", "mai", "juin", "juil.", "août", "sept.", "oct.", "nov.", "déc."] };
const WEEKDAYS = { es: ["dom", "lun", "mar", "mié", "jue", "vie", "sáb"], en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"], fr: ["dim.", "lun.", "mar.", "mer.", "jeu.", "ven.", "sam."] };

export function fmtDate(iso, lang) {
  if (!iso) return null;
  const [y, m, d] = iso.split("-").map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  const wd = WEEKDAYS[lang][dt.getUTCDay()];
  const mo = MONTHS[lang][m - 1];
  return lang === "en" ? `${wd}, ${mo} ${d}` : `${wd} ${d} ${mo}`;
}
export function fmtTime(t, lang) {
  if (!t) return null;
  const [h, m] = t.split(":").map(Number);
  if (lang === "en") return `${((h + 11) % 12) + 1}:${String(m).padStart(2, "0")} ${h >= 12 ? "p.m." : "a.m."}`;
  if (lang === "es") return `${((h + 11) % 12) + 1}:${String(m).padStart(2, "0")} ${h >= 12 ? "p. m." : "a. m."}`;
  return `${h}:${String(m).padStart(2, "0")}`.replace(/^(\d+):00$/, "$1 h");
}
export function eventTime(e, lang) {
  if (e.timeNote && lang === "en") return e.timeNote;
  if (e.timeNote) return e.timeNote.replace(/p\.m\./g, lang === "fr" ? "h" : "p. m.").replace(/ or /g, lang === "fr" ? " ou " : " o ");
  return fmtTime(e.time, lang);
}

/** Builds an .ics file for one event (floating local time in America/Toronto). */
export function icsFor(e, title, description) {
  const pad = (x) => String(x).padStart(2, "0");
  const d = e.date.replace(/-/g, "");
  const esc = (s) => String(s || "").replace(/([,;\\])/g, "\\$1").replace(/\n/g, "\\n");
  const lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Highschool Navigator//EN", "CALSCALE:GREGORIAN", "BEGIN:VEVENT", `UID:${e.id}-${d}@hs-mississauga-navigator`, `DTSTAMP:20260929T120000Z`];
  if (e.time) {
    const [h, m] = e.time.split(":").map(Number);
    let [eh, em] = e.end ? e.end.split(":").map(Number) : [h + 1, m];
    lines.push(`DTSTART;TZID=America/Toronto:${d}T${pad(h)}${pad(m)}00`, `DTEND;TZID=America/Toronto:${d}T${pad(eh)}${pad(em)}00`);
  } else {
    const next = new Date(Date.UTC(+e.date.slice(0, 4), +e.date.slice(5, 7) - 1, +e.date.slice(8, 10) + 1));
    lines.push(`DTSTART;VALUE=DATE:${d}`, `DTEND;VALUE=DATE:${next.getUTCFullYear()}${pad(next.getUTCMonth() + 1)}${pad(next.getUTCDate())}`);
  }
  lines.push(`SUMMARY:${esc(title)}`, `DESCRIPTION:${esc(description)}`, e.addr ? `LOCATION:${esc(e.school + ", " + e.addr)}` : `LOCATION:${esc(e.school)}`, "END:VEVENT", "END:VCALENDAR");
  return lines.join("\r\n");
}
export function downloadIcs(e, title, description) {
  const blob = new Blob([icsFor(e, title, description)], { type: "text/calendar;charset=utf-8" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `info-session-${e.school.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.ics`;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 500);
}
